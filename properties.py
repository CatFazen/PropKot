_h_f0_interp    = interp1d(T_K, h_f0,    kind='linear', bounds_error=True)
_h_f0169_interp = interp1d(T_K, h_f0169, kind='linear', bounds_error=True)

def h(T, f=0):
    if f == 0:
        return float(_h_f0_interp(T))
    elif f == 0.0169:
        return float(_h_f0169_interp(T))
    else:
        raise ValueError(f"f={f} not supported")

#reverse interpolation

_T_from_h_f0_interp    = interp1d(h_f0,    T_K, kind='linear', bounds_error=True)
_T_from_h_f0169_interp = interp1d(h_f0169, T_K, kind='linear', bounds_error=True)


def T_from_h(h_value, f=0):
    if f == 0:
        return float(_T_from_h_f0_interp(h_value))
    elif f == 0.0169:
        return float(_T_from_h_f0169_interp(h_value))
    else:
        raise ValueError(f"f={f} not supported")

def h_at_f(T, f):
    """
    Enthalpy at temperature T (K) and arbitrary fuel-air ratio f.
    Performs 2D interpolation across both T and f using Mattingly f columns. 
    """
    h_at_T = np.array([
        _h_f0_interp(T),
        _h_f0169_interp(T),
        float(interp1d(T_K, h_f0338, kind='linear')(T)),
        float(interp1d(T_K, h_f0507, kind='linear')(T)),
        float(interp1d(T_K, h_f0676, kind='linear')(T)),
    ])
    return float(interp1d(f_values, h_at_T, kind='linear')(f))

def R_gas(f):
    return 287.0  #Kept it at 287 for now, physically less assumptions

def cp(T, f, dT=10.0):
    """
    Cp at constant pressure, cp(T, f), in J/(kg·K).
    """
    h_plus = h_at_f(T + dT, f)
    h_minus = h_at_f(T - dT, f)

    return (h_plus - h_minus) * 1000.0 / (2.0 * dT)

def gamma(T, f):
    """
    Specific heat ratio γ = cp / cv at temperature T and fuel-air ratio f.
    """
    cp_val = cp(T, f)
    R = R_gas(f)
    return cp_val / (cp_val - R)

def T_from_h_at_f(h_value, f):
    """
    2D reverse interpolation by inverting the h_at_f mapping.
    Uses bisection root finding since we can't invert 2D table.
    """
    from scipy.optimize import brentq
    
    # Define a function whose root is the T we want
    def residual(T):
        return h_at_f(T, f) - h_value
    T_solution = brentq(residual, 170.001, 1399.999)
    
    return T_solution

